const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { test } = require('node:test');
const { loadRoutes, req, sqlPath, PGlite } = require('./entertainment-support.cjs');

test('watch rooms: actual API lifecycle, room-only access, host authorization, ordering, SQL integrity and RLS', async () => {
  const db = new PGlite();
  try {
    await db.exec('create role anon; create role authenticated; create role service_role bypassrls; grant usage on schema public to service_role;');
    await db.exec(readFileSync(sqlPath, 'utf8'));
    const api = loadRoutes(db);
    assert.equal((await api.rooms.POST(req('POST', { url: 'https://youtu.be/dQw4w9WgXcQ' }))).status, 401);
    assert.equal((await api.rooms.POST(req('POST', { url: 'https://127.0.0.1/a.mp4' }, null, true))).status, 400);
    const createdResponse = await api.rooms.POST(req('POST', { url: 'https://youtu.be/dQw4w9WgXcQ', title: 'Film', name: 'Görkem' }, null, true));
    assert.equal(createdResponse.status, 201);
    const created = await createdResponse.json(), { room, session: host } = created;
    const ctx = { params: Promise.resolve({ id: room.id }) };
    const roomURL = `/${room.id}`;
    assert.equal(room.source_kind, 'youtube');
    assert.ok(!('invite_hash' in room) && !('owner_id' in room));
    const stored = (await db.query('select invite_hash from watch_rooms')).rows[0];
    assert.notEqual(stored.invite_hash, host.invite);
    assert.equal((await api.room.GET(req('GET', undefined, 'fake', false, roomURL), ctx)).status, 401);
    assert.equal((await api.join.POST(req('POST', { invite: 'invalid', name: 'A' }), ctx)).status, 403);
    assert.equal((await api.join.POST(req('POST', { host: true }), ctx)).status, 401);
    const guest = (await (await api.join.POST(req('POST', { invite: host.invite, name: 'Misafir' }), ctx)).json()).session;
    assert.equal(guest.member.role, 'guest');
    assert.equal((await api.room.PATCH(req('PATCH', { action: 'playback', revision: 0, playing: true, position: 12 }, guest.token), ctx)).status, 403);
    assert.equal((await api.room.PATCH(req('PATCH', { action: 'playback', revision: 0, playing: true, position: 12 }, host.token), ctx)).status, 200);
    assert.equal((await api.room.PATCH(req('PATCH', { action: 'playback', revision: 0, playing: false, position: 12 }, host.token), ctx)).status, 409);
    let snap = await (await api.room.GET(req('GET', undefined, guest.token, false, roomURL), ctx)).json();
    assert.equal(snap.room.playing, true); assert.equal(snap.room.position, 12); assert.equal(snap.members.length, 2);
    assert.ok(snap.members.every(m => !('token_hash' in m)));
    assert.equal((await api.room.POST(req('POST', { kind: 'chat', body: { text: '<script>alert(1)</script>', name: 'Sahte' } }, guest.token), ctx)).status, 200);
    snap = await (await api.room.GET(req('GET', undefined, host.token, false, roomURL), ctx)).json();
    assert.equal(snap.events[0].body.name, 'Misafir'); assert.equal(snap.events[0].body.text, '<script>alert(1)</script>');
    const last = snap.events[0].id;
    assert.equal((await (await api.room.GET(req('GET', undefined, host.token, false, `${roomURL}?after=${last}`), ctx)).json()).events.length, 0);
    assert.equal((await api.room.PATCH(req('PATCH', { action: 'share', active: true, revision: 1 }, host.token), ctx)).status, 200);
    assert.equal((await api.room.POST(req('POST', { kind: 'offer', recipientId: host.member.id, body: { sdp: 'offer' } }, guest.token), ctx)).status, 403);
    assert.equal((await api.room.POST(req('POST', { kind: 'offer', recipientId: guest.member.id, body: { sdp: 'offer' } }, host.token), ctx)).status, 200);
    assert.equal((await api.room.POST(req('POST', { kind: 'answer', recipientId: host.member.id, body: { sdp: 'answer' } }, guest.token), ctx)).status, 200);
    const another = (await (await api.rooms.POST(req('POST', { url: 'https://example.org/video.mp4' }, null, true))).json()).session;
    const otherCtx = { params: Promise.resolve({ id: another.roomId }) };
    assert.equal((await api.room.GET(req('GET', undefined, guest.token), otherCtx)).status, 401);
    assert.equal((await api.room.POST(req('POST', { kind: 'ice', recipientId: another.member.id, body: { candidate: 'ice' } }, host.token), ctx)).status, 404);
    for (let i = 0; i < 6; i++) assert.equal((await api.join.POST(req('POST', { invite: host.invite, name: `Guest ${i}` }), ctx)).status, 200);
    assert.equal((await api.join.POST(req('POST', { invite: host.invite, name: 'Full' }), ctx)).status, 409);
    await db.query('update watch_members set last_seen=$1 where id=$2', ['1970-01-01', guest.member.id]);
    assert.equal((await api.join.POST(req('POST', { invite: host.invite, name: 'Replacement' }), ctx)).status, 200);
    await assert.rejects(db.query('update watch_members set last_seen=now() where id=$1', [guest.member.id]));
    await db.exec('set role anon'); await assert.rejects(db.query('select * from watch_rooms')); await assert.rejects(db.query('select * from watch_events')); await db.exec('reset role');
    await db.exec('set role authenticated'); await assert.rejects(db.query('select * from watch_members')); await db.exec('reset role');
    assert.equal((await api.room.PATCH(req('PATCH', { action: 'close', revision: 2 }, host.token), ctx)).status, 200);
    assert.equal((await api.room.GET(req('GET', undefined, host.token), ctx)).status, 410);
    assert.equal((await api.room.POST(req('POST', { kind: 'chat', body: { text: 'closed' } }, guest.token), ctx)).status, 410);
    await db.query('update watch_rooms set expires_at=$1 where id=$2', ['2000-01-01', room.id]);
    assert.equal((await api.rooms.POST(req('POST', { url: 'https://example.org/new' }, null, true))).status, 201);
    assert.equal((await db.query('select count(*)::int n from watch_members where room_id=$1', [room.id])).rows[0].n, 0);
    const p = api.model.parseSource;
    assert.equal(p('https://www.google.com/url?q=https%3A%2F%2Fyoutu.be%2FdQw4w9WgXcQ').kind, 'youtube');
    assert.equal(p('https://example.org/a.mp4?token=1').kind, 'video');
    assert.equal(p('example.org/watch').kind, 'website');
    for (const invalid of ['javascript:alert(1)', 'https://user:pass@example.org/a', 'https://10.0.0.1/a', 'https://panel.example.com/a']) assert.throws(() => p(invalid, 'https://panel.example.com'));
    assert.equal(api.model.playbackPosition({ position: 20, playing: true, playback_at: '2026-01-01T00:00:00Z' }, Date.parse('2026-01-01T00:00:05Z')), 25);
    assert.equal(api.model.playbackPosition({ position: 20, playing: false, playback_at: '2026-01-01T00:00:00Z' }, Date.parse('2026-01-01T00:00:05Z')), 20);
  } finally { await db.close(); }
});
