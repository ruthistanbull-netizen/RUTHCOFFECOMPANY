-- Repair schema drift for ROSTA platform runtime objects that are referenced by
-- the panel but were missing from the live database even though earlier migration
-- versions were recorded as applied. Additive/idempotent; service-role only.

create table if not exists public.platform_telemetry_events (
  id bigint generated by default as identity primary key,
  source text not null default 'unknown',
  service text not null default 'unknown',
  route text not null default '/',
  kind text not null default 'resource',
  duration_ms integer not null default 0 check (duration_ms >= 0),
  ok boolean not null default true,
  status_code integer,
  trace_id text,
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);
create index if not exists platform_telemetry_events_service_time_idx
  on public.platform_telemetry_events(service, occurred_at desc);
create index if not exists platform_telemetry_events_route_time_idx
  on public.platform_telemetry_events(route, occurred_at desc);
alter table public.platform_telemetry_events enable row level security;
revoke all on public.platform_telemetry_events from public, anon, authenticated;
grant select, insert, update, delete on public.platform_telemetry_events to service_role;
grant usage, select on sequence public.platform_telemetry_events_id_seq to service_role;

create table if not exists public.platform_recovery_drills (
  id uuid primary key default gen_random_uuid(),
  status text not null default 'passed' check (status in ('passed','failed','degraded')),
  checks jsonb not null default '[]'::jsonb,
  missing_objects jsonb not null default '[]'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  ran_at timestamptz not null default now()
);
create index if not exists platform_recovery_drills_ran_at_idx
  on public.platform_recovery_drills(ran_at desc);
alter table public.platform_recovery_drills enable row level security;
revoke all on public.platform_recovery_drills from public, anon, authenticated;
grant select, insert, update, delete on public.platform_recovery_drills to service_role;

create or replace function public.request_panel_sync(
  p_scope text,
  p_reason text default 'data_changed'
)
returns boolean
language plpgsql
security definer
set search_path=public,pg_catalog
as $$
declare
  v_scope text := left(coalesce(nullif(trim(p_scope),''),'general'),80);
  v_reason text := left(coalesce(nullif(trim(p_reason),''),'data_changed'),180);
  v_key text;
begin
  v_key := 'scope:' || v_scope;
  if exists (
    select 1 from public.panel_sync_requests
    where dedupe_key=v_key and status in ('pending','running')
  ) then
    return false;
  end if;

  begin
    insert into public.panel_sync_requests(scope,reason,dedupe_key,status,requested_at)
    values(v_scope,v_reason,v_key,'pending',now());
    return true;
  exception when unique_violation then
    return false;
  end;
end;
$$;
revoke all on function public.request_panel_sync(text,text) from public, anon, authenticated;
grant execute on function public.request_panel_sync(text,text) to service_role;

create or replace function public.claim_panel_sync_lease(
  p_worker_id text,
  p_lease_seconds integer default 75
)
returns boolean
language plpgsql
security definer
set search_path=public,pg_catalog
as $$
declare
  v_acquired boolean := false;
  v_worker text := left(coalesce(nullif(trim(p_worker_id),''),'panel-sync'),180);
begin
  insert into public.platform_leases(name,holder,leased_until,updated_at)
  values(
    'panel-sync-worker',
    v_worker,
    now() + make_interval(secs => greatest(15,least(coalesce(p_lease_seconds,75),3600))),
    now()
  )
  on conflict(name) do update set
    holder=excluded.holder,
    leased_until=excluded.leased_until,
    updated_at=now()
  where public.platform_leases.leased_until <= now()
     or public.platform_leases.holder = excluded.holder
  returning true into v_acquired;
  return coalesce(v_acquired,false);
end;
$$;
revoke all on function public.claim_panel_sync_lease(text,integer) from public, anon, authenticated;
grant execute on function public.claim_panel_sync_lease(text,integer) to service_role;

create or replace function public.release_panel_sync_lease(p_worker_id text)
returns boolean
language plpgsql
security definer
set search_path=public,pg_catalog
as $$
declare
  v_deleted integer := 0;
begin
  delete from public.platform_leases
  where name='panel-sync-worker' and holder=p_worker_id;
  get diagnostics v_deleted = row_count;
  return v_deleted > 0;
end;
$$;
revoke all on function public.release_panel_sync_lease(text) from public, anon, authenticated;
grant execute on function public.release_panel_sync_lease(text) to service_role;

create or replace function public.platform_slo_snapshot()
returns table(
  service text,
  sample_count bigint,
  success_rate numeric,
  p95_ms numeric,
  within_slo boolean
)
language sql
security definer
set search_path=public,pg_catalog
as $$
  select
    t.service,
    count(*)::bigint as sample_count,
    round(avg(case when t.ok then 1.0 else 0.0 end)::numeric,4) as success_rate,
    round(coalesce(percentile_cont(0.95) within group (order by t.duration_ms),0)::numeric,1) as p95_ms,
    (
      avg(case when t.ok then 1.0 else 0.0 end) >= 0.98
      and coalesce(percentile_cont(0.95) within group (order by t.duration_ms),0) <= 5000
    ) as within_slo
  from public.platform_telemetry_events t
  where t.occurred_at >= now() - interval '15 minutes'
  group by t.service
  order by t.service
$$;
revoke all on function public.platform_slo_snapshot() from public, anon, authenticated;
grant execute on function public.platform_slo_snapshot() to service_role;

create or replace function public.platform_error_budget_snapshot()
returns table(
  service text,
  sample_count bigint,
  failed_count bigint,
  error_rate numeric,
  budget_rate numeric,
  exhausted boolean
)
language sql
security definer
set search_path=public,pg_catalog
as $$
  select
    t.service,
    count(*)::bigint as sample_count,
    count(*) filter (where not t.ok)::bigint as failed_count,
    round((count(*) filter (where not t.ok))::numeric / greatest(count(*),1),4) as error_rate,
    0.02::numeric as budget_rate,
    ((count(*) filter (where not t.ok))::numeric / greatest(count(*),1)) > 0.02 as exhausted
  from public.platform_telemetry_events t
  where t.occurred_at >= now() - interval '15 minutes'
  group by t.service
  order by t.service
$$;
revoke all on function public.platform_error_budget_snapshot() from public, anon, authenticated;
grant execute on function public.platform_error_budget_snapshot() to service_role;

create or replace function public.repair_storefront_product_read_models(p_limit integer default 250)
returns jsonb
language plpgsql
security definer
set search_path=public,pg_catalog
as $$
declare
  r record;
  v_repaired integer := 0;
  v_orphan_deleted integer := 0;
  v_active_products integer := 0;
  v_active_models integer := 0;
  v_limit integer := greatest(1,least(coalesce(p_limit,250),1000));
begin
  for r in
    select p.id
    from public.products p
    left join public.storefront_product_read_models m on m.product_id=p.id
    where p.status='active'
      and (m.product_id is null or m.refreshed_at is null or m.refreshed_at < p.updated_at)
    order by p.updated_at asc
    limit v_limit
  loop
    perform public.refresh_storefront_product_read_model(r.id);
    v_repaired := v_repaired + 1;
  end loop;

  delete from public.storefront_product_read_models m
  where not exists (select 1 from public.products p where p.id=m.product_id);
  get diagnostics v_orphan_deleted = row_count;

  select count(*) into v_active_products from public.products where status='active';
  select count(*) into v_active_models
  from public.storefront_product_read_models m
  join public.products p on p.id=m.product_id
  where p.status='active';

  return jsonb_build_object(
    'ok', v_active_models >= v_active_products,
    'repaired', v_repaired,
    'triggerRepairs', 0,
    'orphanDeleted', v_orphan_deleted,
    'changed', v_repaired + v_orphan_deleted,
    'health', jsonb_build_object(
      'healthy', v_active_models >= v_active_products,
      'activeProducts', v_active_products,
      'activeReadModels', v_active_models
    )
  );
end;
$$;
revoke all on function public.repair_storefront_product_read_models(integer) from public, anon, authenticated;
grant execute on function public.repair_storefront_product_read_models(integer) to service_role;
